-- แยก "ชื่อร้านที่เป็นอิโมจิ" ออกจากกัน
--
-- ปัญหา: utf8mb4_unicode_ci (UCA 4.0.0) ไม่ให้น้ำหนักกับอักขระนอกระนาบพื้นฐาน
-- อิโมจิทุกตัวจึงเทียบเท่ากันหมด · ผู้ใช้ที่มีร้านชื่อ 🚀 แล้วสร้างร้านชื่อ 🎉
-- จะถูกพาไปที่ร้าน 🚀 พร้อมข้อความ "ร้านนี้มีอยู่แล้ว ระบบสลับไปใช้งานร้านนี้ให้แล้ว"
-- แล้วข้อมูลที่บันทึกต่อจากนั้นลงผิดร้านทั้งหมด
--
-- utf8mb4_unicode_520_ci (UCA 5.2.0) แยกอิโมจิได้ และยังถือว่า "ร้าน A" = "ร้าน a"
-- เหมือนเดิม (พิมพ์ชื่อร้านที่มีอยู่แล้ว = สลับไปร้านนั้น — พฤติกรรมที่ตั้งใจ)
--
-- ⚠️ รันบน DB ที่มีข้อมูลได้ทันที ไม่กระทบแถวเดิม
-- ⚠️ ถ้ามีร้านสองร้านที่ชื่อ "ซ้ำกัน" ด้วยกติกาเก่าอยู่แล้ว (เช่นอิโมจิคนละตัว)
--    ตอนนี้จะกลายเป็นคนละชื่อ ซึ่งถูกต้อง — unique index ยอมรับได้ ไม่ต้องแก้อะไร

ALTER TABLE shops
    MODIFY COLUMN name VARCHAR(100)
        CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_520_ci NOT NULL;
