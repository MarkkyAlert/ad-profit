-- แยก "ชื่อร้านที่เป็นอิโมจิ" ออกจากกัน
--
-- ปัญหา: utf8mb4_unicode_ci (UCA 4.0.0) ไม่ให้น้ำหนักกับอักขระนอกระนาบพื้นฐาน
-- อิโมจิทุกตัวจึงเทียบเท่ากันหมด · ผู้ใช้ที่มีร้านชื่อ 🚀 แล้วสร้างร้านชื่อ 🎉
-- จะถูกพาไปที่ร้าน 🚀 พร้อมข้อความ "ร้านนี้มีอยู่แล้ว ระบบสลับไปใช้งานร้านนี้ให้แล้ว"
-- แล้วข้อมูลที่บันทึกต่อจากนั้นลงผิดร้านทั้งหมด
--
-- utf8mb4_unicode_520_ci (UCA 5.2.0) แยกอิโมจิได้ และยังถือว่า "ร้าน A" = "ร้าน a"
-- เหมือนเดิม (พิมพ์ชื่อร้านที่มีอยู่แล้ว = สลับไปร้านนั้น — พฤติกรรมที่ตั้งใจ)
--
-- ⚠️⚠️ ทำไมต้องมีขั้นที่ 1 — การเปลี่ยนกติกาไม่ได้ "แยกอย่างเดียว" มันรวมด้วย
--
-- มี 89 คู่อักขระที่กติกาเดิมถือว่า **ต่างกัน** แต่กติกาใหม่ถือว่า **เหมือนกัน**
-- ที่เจอจริงคือกลุ่มภาษาเวียดนาม: D · Đ · Ð · đ (และ 6 กับ ↅ)
-- ผู้ใช้ที่มีร้าน "Da Nang" กับ "Đa Nang" อยู่แล้ว (ถูกต้องตามกติกาเดิม) จะทำให้
-- ALTER ล้มด้วย duplicate key แล้ว migration ไม่ผ่านทั้งไฟล์ — การแก้อิโมจิจึง
-- ไปไม่ถึงเครื่องจริง โดยที่ข้อความ error ไม่ได้พูดถึงชื่อร้านซ้ำเลยสักคำ
-- (เวอร์ชันแรกของไฟล์นี้เขียนว่า "รันบน DB ที่มีข้อมูลได้ทันที" ซึ่งไม่จริง)
--
-- ขั้นที่ 1 เติมเลขต่อท้ายชื่อร้านที่จะชนกัน — **ไม่มีร้านไหนหาย ไม่มีข้อมูลในร้านหาย**
-- ผู้ใช้แค่เห็นชื่อ "Đa Nang #12" แล้วเปลี่ยนกลับเองได้ในหน้าจัดการร้าน
-- (ชื่อที่ยาวจนเติมเลขไม่พอจะถูกตัดท้าย — คำสั่งท้ายไฟล์แสดงรายการที่ถูกเปลี่ยนให้ดู)

-- ── ขั้นที่ 1: กันชื่อที่กติกาใหม่จะถือว่าซ้ำกัน ───────────────────────────
-- ร้านที่ id น้อยสุดของแต่ละกลุ่มเก็บชื่อเดิมไว้ ที่เหลือเติม " #<เลขประจำร้าน>"
--
-- ⚠️ ต่อท้ายด้วย **เลขประจำร้าน** ไม่ใช่ลำดับที่ 2, 3 …
--
-- ลำดับที่ชนกันเองได้: ผู้ใช้ที่มีร้านชื่อ "Da Nang" กับ "Da Nang (2)" อยู่แล้ว
-- (ชื่อรูปแบบเดียวกับที่ migration นี้สร้าง) แล้วมี "Đa Nang" ด้วย → เปลี่ยนเป็น
-- "Đa Nang (2)" ซึ่งชนกับของเดิม ALTER จึงล้ม แล้ว DB ค้างครึ่งทาง (ชื่อเปลี่ยนแล้ว
-- แต่ collation ยังเก่า) · เลขประจำร้านไม่ซ้ำกันทั้งตาราง จึงชนกันเองไม่ได้
--
-- ⚠️ ชื่อที่ยาวจนเติมเลขไม่พอจะถูกตัดท้าย — บอกจำนวนแถวที่โดนไว้ด้านล่าง
-- ไม่ให้เงียบ (ร้านไม่หาย ข้อมูลในร้านไม่หาย เปลี่ยนชื่อกลับเองได้)
UPDATE shops AS s
JOIN (
    SELECT
        id,
        ROW_NUMBER() OVER (
            PARTITION BY user_id, name COLLATE utf8mb4_unicode_520_ci
            ORDER BY id
        ) AS ordinal
    FROM shops
) AS ranked ON ranked.id = s.id
SET s.name = CONCAT(
    LEFT(s.name, 100 - CHAR_LENGTH(CONCAT(' #', s.id))),
    ' #',
    s.id
)
WHERE ranked.ordinal > 1;

-- ── ขั้นที่ 2: เปลี่ยนกติกาการเทียบชื่อ ────────────────────────────────────
ALTER TABLE shops
    MODIFY COLUMN name VARCHAR(100)
        CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_520_ci NOT NULL;

-- ── ชื่อไหนบ้างที่ถูกเปลี่ยน (ดูให้ครบก่อนปิดหน้าจอ) ─────────────────────
SELECT id, user_id, name AS renamed_to
FROM shops
WHERE name LIKE CONCAT('% #', id);

